"""Score the student-filter extractor against the adjudicated labels (PR 4).

  cd api && .venv/bin/python -m scripts.eval_extraction [--split dev|heldout|all] [--write]

Precision/recall per field. For booleans, a "positive" is a stated True; for the other
fields a prediction counts as correct only when it equals the label exactly, and an
unknown (None) is never scored as a prediction. --write regenerates
docs/extraction_eval.md from the dev and held-out results.
"""
import argparse
import gzip
import json
from pathlib import Path

from app.ingest.eligibility import extract_eligibility

ROOT = Path(__file__).resolve().parent.parent
SET = ROOT / "tests" / "fixtures" / "extraction_eval"
DOC = ROOT.parent / "docs" / "extraction_eval.md"
FIELDS = ["term", "degree_levels", "ms_phd_only", "grad_years", "us_citizen_required",
          "us_person_required", "clearance_required", "workplace_type", "country"]
# The UI gate: a field ships only with held-out precision >= 0.9 on at least this many
# predictions.
MIN_PRECISION, MIN_SUPPORT = 0.9, 8


def _hints(row: dict) -> dict:
    h = row.get("ats_hints") or {}
    return {"workplace_type": h.get("workplaceType"), "is_remote": h.get("isRemote"), "country": h.get("country")}


def _view(d: dict, field: str):
    """A comparable value for one field (None = unknown)."""
    if field == "term":
        return (d.get("term_season"), d.get("term_year")) if d.get("term_season") else None
    if field == "degree_levels":
        return tuple(sorted(d["degree_levels"])) if d.get("degree_levels") else None
    if field == "ms_phd_only":
        levels = set(d.get("degree_levels") or [])
        return (bool(levels) and "bachelor" not in levels) if levels else None
    if field == "grad_years":
        return (d.get("grad_year_min"), d.get("grad_year_max")) if d.get("grad_year_min") else None
    return d.get(field)


def score(split: str) -> dict:
    rows = [json.loads(l) for l in gzip.open(SET / "postings.jsonl.gz", "rt")]
    labels = {json.loads(l)["id"]: json.loads(l) for l in open(SET / "labels.jsonl")}
    out = {}
    for field in FIELDS:
        tp = fp = fn = 0
        errors = []
        for r in rows:
            if split != "all" and r["split"] != split:
                continue
            pred = _view(extract_eligibility(r["title"], r["location"], r["text"], _hints(r)).as_columns(), field)
            gold = _view(labels[r["id"]], field)
            boolean = isinstance(gold, bool) or isinstance(pred, bool)
            if boolean:
                # Precision/recall of the positive class (a stated requirement).
                if pred is True and gold is True:
                    tp += 1
                elif pred is True:
                    fp += 1
                    errors.append((r["id"], pred, gold))
                elif gold is True:
                    fn += 1
                    errors.append((r["id"], pred, gold))
            else:
                if pred is not None and pred == gold:
                    tp += 1
                elif pred is not None:
                    fp += 1
                    errors.append((r["id"], pred, gold))
                elif gold is not None:
                    fn += 1
                    errors.append((r["id"], pred, gold))
        prec = tp / (tp + fp) if tp + fp else None
        rec = tp / (tp + fn) if tp + fn else None
        out[field] = {"tp": tp, "fp": fp, "fn": fn, "precision": prec, "recall": rec, "errors": errors}
    return out


def _fmt(x):
    return "n/a" if x is None else f"{x:.2f}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--split", default="dev", choices=["dev", "heldout", "all"])
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()
    res = score(args.split)
    for f, r in res.items():
        print(f"{f:22} P={_fmt(r['precision'])} R={_fmt(r['recall'])} tp={r['tp']} fp={r['fp']} fn={r['fn']}")
        for e in r["errors"][:6]:
            print("     ", e)
    if args.write:
        write_doc()


def write_doc() -> None:
    dev, held = score("dev"), score("heldout")
    rows = [json.loads(l) for l in gzip.open(SET / "postings.jsonl.gz", "rt")]
    lines = [
        "# Student-filter extraction eval (PR 4)",
        "",
        "Generated by `cd api && .venv/bin/python -m scripts.eval_extraction --write`. Do not edit by hand.",
        "",
        f"**Set:** {len(rows)} real postings (the 119 labeled intern postings from `docs/pay_eval.md` plus the",
        "PR 1 board fixtures), committed at `api/tests/fixtures/extraction_eval/`. Split by a hash of the id:",
        f"{sum(r['split']=='dev' for r in rows)} dev (rules written and tuned against these) and "
        f"{sum(r['split']=='heldout' for r in rows)} held out (scored, never tuned on).",
        "",
        "**Labels:** two independent labelers followed `docs/extraction_labeling_guide.md` without seeing",
        "the extractor or each other (`labels_a.jsonl`, `labels_b.jsonl`); every disagreement was",
        "adjudicated by a third reader against the posting text (`labels.jsonl`, `adjudication.md`).",
        "",
        "**Scoring:** booleans score the stated requirement (True) as the positive class. Other fields",
        "count a prediction as correct only on an exact match; an unknown is never a prediction.",
        f"**UI gate:** a field ships only with held-out precision ≥ {MIN_PRECISION} on ≥ {MIN_SUPPORT} predictions.",
        "",
        "| Field | Dev P | Dev R | Held-out P | Held-out R | Held-out predictions (tp+fp) | Ships in UI |",
        "|---|---|---|---|---|---|---|",
    ]
    for f in FIELDS:
        d, h = dev[f], held[f]
        n = h["tp"] + h["fp"]
        ok = h["precision"] is not None and h["precision"] >= MIN_PRECISION and n >= MIN_SUPPORT
        lines.append(f"| `{f}` | {_fmt(d['precision'])} | {_fmt(d['recall'])} | {_fmt(h['precision'])} | "
                     f"{_fmt(h['recall'])} | {n} | {'**yes**' if ok else 'no'} |")
    lines += [
        "",
        "## Changes made after the first held-out scoring",
        "",
        "Held-out results were scored once. Two rule changes came after that, both driven by",
        "tests on dev postings, not by held-out errors:",
        "",
        "- a bug: a Lever `country` field is an ISO code, and `\"CA\"` (Canada) was read as",
        "  California. Fixing it moved held-out `country` from 0.98/0.98 to 1.00/0.98 (the Waabi,",
        "  Toronto posting);",
        "- pay-table cells (\"Bachelor's Degree\" alone on a line next to a rate) no longer count",
        "  as degree requirements (a dev posting, PsiQuantum).",
        "",
        "No other held-out number changed.",
    ]
    lines += ["", "## Held-out errors", "", "(id, predicted, labeled)", ""]
    for f in FIELDS:
        errs = held[f]["errors"]
        if errs:
            lines.append(f"- `{f}`: " + "; ".join(f"`{e[0]}` {e[1]!r} vs {e[2]!r}" for e in errs[:8]))
    DOC.write_text("\n".join(lines) + "\n")
    print(f"wrote {DOC}")


if __name__ == "__main__":
    main()
